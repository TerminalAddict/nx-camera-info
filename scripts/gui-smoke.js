(async () => {
  const sleep = ms => new Promise(resolve => setTimeout(resolve,ms));
  const wait = async (predicate, label) => { for(let i=0;i<300;i++){ if(predicate()) return; await sleep(100); } throw new Error('Timeout: '+label); };
  await wait(() => window.appReady, 'application ready');
  const { Call } = await import('/wails/runtime.js');
  const harness = (name,...args) => Call.ByName('main.GUIHarness.'+name,...args);
  const $ = id => document.getElementById(id);
  const assert = (condition,message) => { if(!condition) throw new Error(message); };
  const click = async id => { $(id).click(); await sleep(100); await wait(() => document.body.getAttribute('aria-busy') === 'false',id); };
  const capture = async name => {
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
    await sleep(700); await harness('Capture',name);
  };
  const updateClick = async id => { $(id).click(); await wait(() => !$('check-updates').disabled,id); };
  try {
    await click('about-open');
    assert($('about-dialog').open && $('author-name').textContent === 'Paul Willard','About did not open');
    assert($('about-version').textContent === $('version').textContent.replace('Version ',''),'About version disagrees');
    assert((await harness('UpdateEvidence')).requests === 0,'About made an unsolicited network request');
    assert(document.querySelector('.about-author img').naturalWidth > 0,'author portrait not loaded');
    await capture('about');
    document.querySelector('[data-link=author]').click(); await sleep(100);
    assert((await harness('UpdateEvidence')).openedLink === 'https://paulwillard.nz/','author link was not opened externally');
    await harness('Select','update-current'); await updateClick('check-updates');
    assert($('update-status').textContent.includes('up to date') && $('update-offer').hidden,'current release handling failed');
    await harness('Select','update-offline'); await updateClick('check-updates');
    assert(!$('update-error').hidden && $('update-offer').hidden,'offline failure not shown');
    await harness('Select','update-available'); await updateClick('check-updates');
    assert(!$('update-offer').hidden && $('update-package').value.includes('99.0.0'),'new release not offered');
    await capture('update');
    await harness('Select','cancel-update'); await updateClick('download-update');
    assert($('update-status').textContent.includes('cancelled'),'save cancellation failed');
    await harness('Select','update-slow'); $('download-update').click();
    await wait(() => !$('update-progress-wrap').hidden,'download progress');
    $('cancel-update').click(); await wait(() => !$('check-updates').disabled,'download cancelled');
    assert($('update-status').textContent.includes('cancelled'),'network cancellation failed');
    await harness('Select','update-corrupt'); await updateClick('download-update');
    assert(!$('update-error').hidden && $('update-error').textContent.includes('SHA-256'),'corrupt installer accepted');
    assert((await harness('UpdateEvidence')).download === '', 'failed download left an installer');
    await harness('Select','update-available'); await updateClick('download-update');
    assert(!$('update-saved').hidden && $('update-status').textContent.includes('verified'),'verified download not completed');
    assert((await harness('UpdateEvidence')).download === 'synthetic update installer; never executed','saved installer bytes differ');
    $('show-update').click(); await sleep(100);
    assert((await harness('UpdateEvidence')).shownFile.endsWith('update-installer.test'),'download not revealed');
    $('release-link').click(); await sleep(100);
    assert((await harness('UpdateEvidence')).openedLink.endsWith('/releases/tag/v99.0.0'),'wrong release link');
    await click('about-close'); assert(!$('about-dialog').open,'About did not close');
    assert($('export').disabled, 'export enabled without database');
    await harness('Select','cancel'); await click('open'); assert($('filename').textContent === 'No database selected','cancel changed database');
    await harness('Select','normal'); await click('open');
    assert($('rows').children.length === 8,'wrong camera count');
    assert(!document.body.textContent.includes('demo-password'),'password leaked in masked view');
    await capture('inventory');
    await click('nav-users');
    assert($('page-title').textContent === 'Users' && $('table-wrap').hidden,'users navigation failed');
    assert($('report-panel').textContent.includes('Power User') && $('report-panel').textContent.includes('operator@example.invalid'),'user roles or email missing');
    await capture('users');
    await click('nav-system');
    assert($('report-panel').textContent.includes('Ubuntu 24.04 LTS') && $('report-panel').textContent.includes('192.168.50.10'),'system information missing');
    await capture('servers');
    await click('nav-storage');
    assert($('report-panel').textContent.includes('/mnt/backup/HD Witness Media'),'storage missing');
    await capture('storage');
    await click('nav-licenses');
    assert($('report-panel').textContent.includes('DEMO-ONLY-0000-0001') && $('report-panel').textContent.includes('Unavailable from database'),'licence keys or unknown activation counts missing');
    document.querySelector('#report-panel .row-details').click();
    assert($('details').textContent.includes('DEMO-NOT-A-VALID-LICENCE') && $('details').textContent.includes('DEMO-HARDWARE-ID'),'licence details omitted stored fields');
    $('details-dialog').close(); await capture('licenses');
    await click('nav-cameras');
    await click('reveal'); assert($('rows').textContent.includes('demo-password'),'reveal failed');
    document.querySelector('.row-details').click();
    assert($('details-dialog').open && $('details').textContent.includes('demo-password'),'camera details failed');
    $('details-dialog').close();
    await click('reveal'); assert(!document.body.textContent.includes('demo-password'),'hide failed');
    $('filter').value='Hikvision'; await click('apply-filter'); assert($('rows').children.length===2,'filter failed');
    await capture('filtered');
    await click('export'); assert($('export-dialog').open,'export dialog missing');
    await capture('export');
    await click('save-export'); const csv = await harness('ReadExport','csv');
    assert(csv.includes('Hikvision')&&!csv.includes('demo-password')&&!csv.includes('Reception'),'masked filtered CSV incorrect');
    assert(csv.startsWith('record_type,record_id,field,value') && csv.includes('DEMO-ONLY-0000-0001') && csv.includes('Power User'),'full CSV omitted new sections');
    await click('reveal'); await click('export'); document.querySelector('input[value=json]').checked=true;
    await click('save-export'); const exported = JSON.parse(await harness('ReadExport','json'));
    assert(exported.cameras.length===2 && exported.cameras[0].password==='demo-password','revealed JSON incorrect');
    assert(exported.users.length===3 && exported.servers.length===1 && exported.storage.length===3 && exported.licenses.length===2,'JSON omitted new sections');
    assert(exported.licenses[0].activations_remaining===null,'unknown activations must remain null');
    await click('export'); await click('save-export'); assert(!$('error').hidden&&$('error').textContent.includes('already exists'),'overwrite not refused');
    await click('clear-filter'); await click('virtual'); assert($('rows').children.length===9,'virtual camera toggle failed');
    await click('refresh'); assert($('rows').children.length===9,'refresh lost options');
    await harness('Select','invalid'); await click('open'); assert(!$('error').hidden,'invalid database not reported'); assert($('rows').children.length===9,'invalid open discarded snapshot');
    await click('close'); assert($('rows').children.length===0 && $('export').disabled && $('report-panel').children.length===0,'close did not clear data');
    await harness('Done','');
  } catch(error) { await harness('Done',String(error) + '\n' + (error.stack || '')); }
})().catch(error => console.error(error));
